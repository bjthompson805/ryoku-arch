guint16 ryo_spice_keymap_scancode(guint hardware_keycode) {
	/* GTK's hardware keycode is the evdev keycode offset by 8 (the same
	 * XKB convention X11 uses, kept for compatibility on Wayland). */
	if (hardware_keycode < 8) {
		return 0;
	}
	guint evdev_keycode = hardware_keycode - 8;
	if (evdev_keycode >= G_N_ELEMENTS(evdev_to_spice_scancode)) {
		return 0;
	}
	return evdev_to_spice_scancode[evdev_keycode];
}
